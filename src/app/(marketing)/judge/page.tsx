import type { Metadata } from "next";
import Link from "next/link";
import { Section, Eyebrow, H2, Lead } from "@/components/marketing/sections";
import { JudgeAccessForm } from "@/components/marketing/judge-access-form";
import { env, integrationStatuses } from "@/lib/env";
import { db } from "@/lib/db";

export const metadata: Metadata = { title: "For judges", description: "Enter the preconfigured PACT demonstration workspace with the access code from the Devpost testing instructions." };
export const dynamic = "force-dynamic";

async function judgeState(): Promise<{ provisioned: boolean; reason?: string; paypal: boolean; gemini: boolean }> {
  try {
    const e = env();
    const statuses = integrationStatuses();
    const paypal = statuses.find((s) => s.name === "paypal")?.configured ?? false;
    const gemini = statuses.find((s) => s.name === "gemini")?.configured ?? false;
    if (!e.JUDGE_ACCESS_CODE || !e.JUDGE_EMAIL) return { provisioned: false, reason: "The judge access code is not configured on this deployment.", paypal, gemini };
    const judge = await db.user.findUnique({ where: { email: e.JUDGE_EMAIL.toLowerCase() }, include: { memberships: { include: { organization: true } } } });
    const demo = judge?.memberships.find((m) => m.organization.kind === "JUDGE_DEMO");
    if (!demo) return { provisioned: false, reason: "The judge account has not been seeded yet.", paypal, gemini };
    return { provisioned: true, paypal, gemini };
  } catch (error) {
    return { provisioned: false, reason: error instanceof Error ? error.message : "Configuration error.", paypal: false, gemini: false };
  }
}

export default async function JudgePage() {
  const state = await judgeState();
  const steps = [
    ["Create a contract", "The New contract page is prefilled with the landing page objective and a USD 60 budget. Keep the Defective first draft scenario and generate the contract with Gemini."],
    ["Approve it", "Read the criteria, then approve. The content hash is frozen and the Buyer Agent starts negotiating with a worker."],
    ["Authorize with PayPal sandbox", "Approve the order as the sandbox payer from the testing instructions. Funds are held, not captured."],
    ["Watch verification block the payment", "The worker's first draft leaves the contact form unwired. The verifier's browser check fails, the policy engine records DENY, and the correction request goes back to the worker."],
    ["Watch the correction pass", "Attempt 2 runs as a separate record. When it passes, the policy engine allows capture; approve if it asks you."],
    ["Open the receipt", "The signed Proof of Work Receipt links the contract hash, deliverable hash, evidence, decision, and PayPal references. Verify it on the public page."],
  ];
  return (
    <>
      <Section className="pb-10">
        <div className="grid gap-10 lg:grid-cols-[1fr_420px]">
          <div>
            <Eyebrow>For hackathon judges</Eyebrow>
            <H2>A preconfigured workspace, no sign-up</H2>
            <Lead>The demonstration workspace already has a spending policy, the three platform agents, and a restricted admin account. Everything you do in it is real: the contract is generated by Gemini, the verifier runs a real browser, and the payment is a real PayPal sandbox authorization and capture. The workspace is labelled as a demonstration throughout the interface.</Lead>
            <ol className="mt-8 space-y-4">
              {steps.map(([title, body], i) => (
                <li key={title} className="flex gap-4">
                  <span className="flex h-7 w-7 shrink-0 items-center justify-center rounded-full bg-navy text-xs font-semibold text-white dark:text-[#0a1628]">{i + 1}</span>
                  <div>
                    <p className="text-sm font-semibold text-ink">{title}</p>
                    <p className="text-sm leading-relaxed text-muted">{body}</p>
                  </div>
                </li>
              ))}
            </ol>
            <p className="mt-8 text-sm text-muted">
              Prefer your own workspace? <Link href="/sign-up" className="font-medium text-navy hover:underline">Create an account</Link> and run the same flow. The full walkthrough is in{" "}
              <Link href="https://github.com/MaatlaHealth/Pact/blob/main/JUDGE_ACCESS.md" className="font-medium text-navy hover:underline">JUDGE_ACCESS.md</Link>.
            </p>
          </div>
          <div className="lg:pt-10">
            <JudgeAccessForm provisioned={state.provisioned} reason={state.reason} paypal={state.paypal} gemini={state.gemini} />
          </div>
        </div>
      </Section>
    </>
  );
}
